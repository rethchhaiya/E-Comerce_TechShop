CREATE TABLE product_variants(
    -- automatic generate id and make it unique
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- product id from products table as a foreign key
    product_id BIGINT NOT NULL REFERENCES products(id) ON DELETE CASCADE,
    
    sku VARCHAR(100) NOT NULL,
    variant_name VARCHAR(255) NOT NULL,
    
    -- numeric(precision, scale)
    -- this is data guard
    price NUMERIC(10, 2) NOT NULL CHECK (price >= 0),
    cost NUMERIC(10, 2) NOT NULL CHECK (cost >= 0),
    stock_quantity INT NOT NULL DEFAULT 0 CHECK (stock_quantity >= 0),
    
    is_active BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    -- define a rule for data base from having a duplicate sku
    CONSTRAINT uq_product_variants_sku UNIQUE (sku)
);

-- this tell data base to create an index and make it query data faster
CREATE INDEX idx_product_variants_product_id ON product_variants(product_id);